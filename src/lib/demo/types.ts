/**
 * Тип готового примера, который страница передаёт в компонент инструмента.
 *
 * Живёт отдельно от engineSample.ts намеренно: тот импортирует генераторы всех
 * четырёх движковых инструментов, и компоненту, которому нужен только тип,
 * незачем тянуть их за собой. Скрипт выноса инструментов в отдельные
 * репозитории собирает зависимости обходом импортов, и без этого разделения
 * репозиторий одного инструмента забирал бы код остальных трёх.
 */
