import { describe, expect, it } from "vitest";
import { capitalizeSentences, fill, sentences, truncate } from "./text";

describe("fill", () => {
  it("подставляет слоты", () => {
    expect(fill("Ищу {keyword}.", { keyword: "маникюр" })).toBe("Ищу маникюр.");
  });

  it("схлопывает незаполненный слот вместо того, чтобы показать его пользователю", () => {
    expect(fill("Ищу {keyword} {missing}.", { keyword: "лиды" })).toBe("Ищу лиды.");
  });

  it("не раскрывает слоты, пришедшие из пользовательского текста", () => {
    // Иначе введённое пользователем «{outcome}» стало бы настоящей подстановкой.
    const out = fill("Тема — {keyword}.", { keyword: "{outcome}", outcome: "секрет" });
    expect(out).toBe("Тема — {outcome}.");
    expect(out).not.toContain("секрет");
  });

  it("ставит заглавную в начале предложения после подстановки", () => {
    expect(fill("Цель: {a}. {b} — верно?", { a: "рост", b: "маникюр" })).toBe(
      "Цель: рост. Маникюр — верно?"
    );
  });

  it("не трогает бренды, написанные не в нижнем регистре", () => {
    expect(fill("Тема. {k} — хорошо.", { k: "iPhone" })).toBe("Тема. iPhone — хорошо.");
  });

  it("не ставит заглавную после двоеточия и тире — в русском там строчная", () => {
    expect(fill("Задача: {a}", { a: "рост выручки" })).toBe("Задача: рост выручки");
  });

  it("убирает пробел перед знаком препинания", () => {
    expect(fill("Тема {k} , дальше", { k: "" })).toBe("Тема, дальше");
  });
});

describe("truncate", () => {
  it("не трогает короткое", () => {
    expect(truncate("коротко", 50)).toBe("коротко");
  });

  it("режет по границе слова", () => {
    expect(truncate("одно два три четыре пять", 14)).toBe("одно два три…");
  });
});

describe("sentences", () => {
  it("делит по точкам и переводам строки", () => {
    expect(sentences("Первое. Второе!\nТретье?")).toEqual([
      "Первое.",
      "Второе!",
      "Третье?",
    ]);
  });

  it("выкидывает пустые куски", () => {
    expect(sentences("   ")).toEqual([]);
  });
});

describe("capitalizeSentences", () => {
  it("поднимает первую букву строки", () => {
    expect(capitalizeSentences("привет")).toBe("Привет");
  });
});
